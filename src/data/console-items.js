export function isConsoleKitItem(item) {
  if (!item?.id) return false;
  return CONSOLE_KIT_ALLOW.has(String(item.id).toLowerCase());
}

export function consoleKitExtras() {
  return EXTRA_ITEMS.filter((item) => CONSOLE_KIT_ALLOW.has(item.id));
}

